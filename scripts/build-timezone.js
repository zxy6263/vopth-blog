'use strict';

/**
 * 把构建时区固定为 Asia/Shanghai。
 * ===========================================================================
 *
 * 为什么需要这个文件
 * ---------------------------------------------------------------------------
 * Hexo 的 permalink（`_config.yml` 里的 `:year/:month/:day/:title/`）取的是
 * **Date 对象的本地时间**，而 `_config.yml` 里的 `timezone: 'Asia/Shanghai'`
 * 【管不住它】。
 *
 * 后果：同一份代码，构建机时区不同 → 生成的文章 URL 不同。
 *
 *   本机构建（China Standard Time, UTC+8）  ->  /2026/10/03/hello-vopth/
 *   Cloudflare 构建（UTC）                  ->  /2026/10/02/hello-vopth/
 *
 * 这会真实地坏事：本地预览里首页链接是 /10/03/，而线上文章实际在 /10/02/，
 * 于是**线上所有文章页 404**，只有 /about/、/archives/ 这类不依赖日期的页面正常。
 *
 * 已实测确认（本地用 TZ=UTC 复现）：
 *   npm run build                        -> /2026/10/03/…
 *   $env:TZ='UTC'; npm run build         -> /2026/10/02/…   ← 与线上一致
 *
 * 为什么放 scripts/ 而不是改控制台设置
 * ---------------------------------------------------------------------------
 * 设 Cloudflare 的构建环境变量 `TZ=Asia/Shanghai` 也能修，但那是**控制台里的
 * 隐形依赖**：哪天有人重建项目、换个账号、或者忘了，URL 就会再漂一次，
 * 而且漂了不报错（正是本项目最怕的「静默失效」）。
 *
 * 放在 `scripts/` 里则跟着代码走，本地和线上走同一条路径，结果确定。
 * Hexo 会自动加载 `scripts/` 下的所有 .js，不需要任何配置。
 *
 * 文件名刻意用 `build-` 开头：Hexo 按文件名顺序加载脚本，这个名字排在
 * post-author / post-cover 之前，能保证在生成任何文章之前就设好。
 */

process.env.TZ = 'Asia/Shanghai';
